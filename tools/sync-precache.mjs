/**
 * Rewrites the PRECACHE list in js/cache-policy.js from what is actually on
 * disk. Run after adding or removing any module, stylesheet or data file:
 *   node tools/sync-precache.mjs
 * The cache test fails loudly if this is forgotten.
 */
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';

const walk = dir => readdirSync(dir).flatMap(f => {
  const p = `${dir}/${f}`;
  return statSync(p).isDirectory() ? walk(p) : [p];
});

const files = [...walk('js'), ...walk('data'), ...walk('assets/css')]
  .filter(p => /\.(js|json|css)$/.test(p))
  .filter(p => !p.endsWith('sw.js'))
  .sort();

const entries = [
  './', './index.html', './manifest.webmanifest',
  './assets/img/cockpit.jpg', './assets/img/clouddeck.jpg', './assets/img/icon.svg',
  ...files.map(p => './' + p),
];

const src = readFileSync('js/cache-policy.js', 'utf8');
const start = src.indexOf('export const PRECACHE = [');
const end = src.indexOf('];', start) + 2;
const block = 'export const PRECACHE = [\n'
  + '  // Generated by tools/sync-precache.mjs — every asset needed for a cold\n'
  + '  // offline boot. A test asserts this never drifts from what is on disk.\n'
  + entries.map(e => `  '${e}',`).join('\n')
  + '\n];';

writeFileSync('js/cache-policy.js', src.slice(0, start) + block + src.slice(end));
console.log(`precache: ${entries.length} entries`);
